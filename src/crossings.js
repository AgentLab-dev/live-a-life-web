export function bankOf(y) {
  if (y < CREEK.y - 4) return "north";
  if (y > CREEK.y + CREEK.h + 4) return "south";
  return "";
}

export function nearCreek(y) {
  return y >= CREEK.y - 48 && y <= CREEK.y + CREEK.h + 48;
}

